export const getProduct = (slug: string) => products.find((p) => p.slug === slug);

export const byCategory = (slug: string) =>
  slug === "all" ? products : products.filter((p) => p.category === slug);

export const totalStock = (p: Product) =>
  (p?.variants || []).reduce((sum, v) => {
    if (v.colours && v.colours.length > 0) {
      return sum + v.colours.reduce((s, c) => s + (c.stockQty || 0), 0);
    }
    return sum + (v.stockQty ?? 0);
  }, 0);

export const relatedTo = (p: Product) =>
  products.filter((x) => x.id !== p.id && x.category === p.category).slice(0, 4);

export const bestSellers = products.filter((p) => p.isBestseller || (p.rating && p.rating >= 4.7));
export const newArrivals = products.filter((p) => p.isNew);
export const onSaleProducts = products.filter((p) => !!p.compareAtPrice);
