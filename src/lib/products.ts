import type { Product, ColourVariant } from "./types";

const sizes = (spec: Record<number, number>, defaultColours: string[] = ["White", "Black"]) =>
  Object.entries(spec).map(([size, stockQty], idx) => {
    const s = Number(size);
    const cols = defaultColours && defaultColours.length > 0 ? defaultColours : ["White", "Black"];
    const colours: ColourVariant[] = cols.map((col, colIdx) => {
      let qty = 0;
      if (stockQty > 0) {
        if (cols.length === 2) {
          if (s === 40) {
            const half = Math.floor(stockQty / 2);
            qty = colIdx === 0 ? stockQty - half : half;
          } else if (idx % 3 === 0) {
            qty = colIdx === 0 ? stockQty : 0;
          } else if (idx % 3 === 1) {
            qty = colIdx === 1 ? stockQty : 0;
          } else {
            const half = Math.floor(stockQty / 2);
            qty = colIdx === 0 ? stockQty - half : half;
          }
        } else {
          const base = Math.floor(stockQty / cols.length);
          qty = base + (colIdx === 0 ? stockQty % cols.length : 0);
        }
      }
      return {
        colour: col,
        sku: `NS-${s}-${col.replace(/[^A-Za-z0-9]/g, "").slice(0, 3).toUpperCase()}`,
        stockQty: qty,
      };
    });
    return {
      size: s,
      sku: `NS-${s}`,
      stockQty,
      colours,
    };
  });

